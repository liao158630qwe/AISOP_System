const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const playwright=require(path.join(process.env.USERPROFILE,'.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright'));
const base=process.env.TRAIN_TEST_BASE,output=process.env.TRAIN_TEST_OUTPUT;
if(!base||!output)throw new Error('Run with tools/test-training-ui.py');
(async()=>{
  const browser=await playwright.chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1050}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.setDefaultTimeout(20000);
  const screenshot=name=>page.screenshot({path:path.join(output,name+'.png'),fullPage:true});
  try{
    await page.goto(base+'/admin');
    await page.locator('#workspace-login [name=username]').fill(process.env.APP_USERNAME);
    await page.locator('#workspace-login [name=password]').fill(process.env.APP_PASSWORD);
    await page.locator('#workspace-login button[type=submit]').click();
    await page.getByRole('link',{name:'工业模型训练 ↗'}).click();
    await page.locator('#training-content').waitFor({state:'visible'});
    await page.locator('#training-task').selectOption('feature-classify');
    await page.locator('#training-name').fill('接口验证夹具 · 非现场精度');
    await page.locator('#training-dataset').fill(process.env.TRAIN_FEATURE_DATA);
    await page.locator('#training-feature-schema').fill('test-fixture-v1');
    await page.locator('.training-policy > summary').click();
    assert.equal(await page.locator('#policy-negatives').isVisible(),false);
    for(const [id,value] of [['policy-batches','2'],['policy-classes','5']])await page.locator('#'+id).fill(value);
    await page.locator('#training-submit').click();
    await page.waitForFunction(()=>document.querySelector('#training-runs').textContent.includes('测试通过 · 待现场验收'),null,{timeout:120000});
    await page.locator('[data-detail]').first().click();
    await page.locator('#training-detail-body .training-detail-summary').waitFor();
    await screenshot('feature-candidate-detail');
    assert.ok((await page.locator('#training-detail-body').innerText()).includes('需要专用推理适配器'));
    await page.locator('#training-close').click();
    // A real one-epoch visual run over generated random fixture images must fail
    // its 95% per-class gate. This proves plumbing, not production model quality.
    await page.locator('#training-task').selectOption('detect');
    await page.locator('#policy-negatives').fill('5');
    await page.locator('#training-name').fill('视觉链路验证夹具 · 应被门禁拒绝');
    await page.locator('#training-dataset').fill(process.env.TRAIN_VISUAL_DATA);
    await page.locator('#training-pretrained').selectOption('models/yolo11n.pt');
    await page.locator('#training-epochs').fill('1');
    await page.locator('#training-imgsz').evaluate(el=>{el.add(new Option('128（验证夹具）','128'));});
    await page.locator('#training-imgsz').selectOption('128');
    await page.locator('#training-submit').click();
    await page.waitForFunction(()=>document.querySelector('#training-runs').textContent.includes('测试未达标'),null,{timeout:240000});
    assert.ok(!(await page.locator('#training-runs').innerText()).includes('训练进程退出'));
    await page.locator('[data-detail]').first().click();
    await page.locator('#training-detail-body .training-detail-summary').waitFor();
    await screenshot('visual-test-gate');
    await page.locator('#training-close').click();
    await screenshot('training-desktop');
    await page.reload();
    await page.locator('.training-run').nth(1).waitFor();
    const runs=await page.evaluate(async()=>{const r=await window.Workspace.request('/admin/training-runs');return Promise.all(r.items.map(item=>window.Workspace.request('/admin/training-runs/'+item.id)));});
    assert.equal(runs.length,2);
    assert.equal(runs[0].state,'REJECTED');
    assert.equal(runs[1].state,'CANDIDATE');
    assert.ok(runs.every(r=>!r.model_id));
    assert.ok(runs.every(r=>r.card.execution.torch_threads===2),'Host helper threads must retain the limit through model.val');
    assert.ok(runs.every(r=>r.card.execution.device.startsWith('cuda:')&&r.card.execution.cpuFallback===false),'Both training pipelines must use CUDA without CPU fallback');
    assert.equal(await page.evaluate(async()=>(await window.Workspace.request('/admin/models')).items.length),0);
    await page.setViewportSize({width:390,height:844});
    await page.waitForFunction(()=>document.querySelector('#training-pretrained').options.length>1);
    await screenshot('training-mobile');
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile must fit viewport');
    await page.locator('#account-button').click();
    await page.locator('#training-locked').waitFor({state:'visible'});
    assert.equal(await page.locator('.training-run').count(),0);
    assert.deepEqual(errors,[]);
    fs.writeFileSync(path.join(output,'verification.json'),JSON.stringify({scope:'Generated test fixtures: workflow verification only, not field accuracy',passed:true,pageErrors:errors,runs},null,2));
    console.log('Training UI, isolated CUDA feature/visual training, gate rejection, persistence and mobile checks passed.');
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
