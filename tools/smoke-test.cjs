    await page.locator('[data-resolve="1"]').click();
    assert.equal(await page.locator('#metric-alerts').textContent(),'1');
    await page.locator('[data-confirm="1"]').click();
    assert.equal(await page.locator('#metric-alerts').textContent(),'0');
    await page.locator('[data-action="workflow"]').click();
    await page.locator('#flow-name').fill('验收测试装配流程');
    await page.locator('[data-step-duration]').first().fill('6');
    await page.locator('[data-action="add-step"]').click();
    await page.locator('[data-step-name]').last().fill('最终质量检查');
    await page.locator('#workflow-form button[type="submit"]').click();
    assert.equal(await page.locator('#workflow-name').textContent(),'验收测试装配流程');
    assert.equal(await page.locator('.step').count(),4);
    await page.reload();await page.waitForFunction(()=>document.querySelector('#source-video').readyState>=2);
    assert.equal(await page.locator('#workflow-name').textContent(),'验收测试装配流程');
    await page.locator('[data-action="workflow"]').click();
    await page.locator('[data-action="reset-workflow"]').click();
    await page.locator('#workflow-form button[type="submit"]').click();
    const downloadPromise=page.waitForEvent('download');
    await page.locator('[data-action="export-alerts"]').click();
    const download=await downloadPromise;const downloadPath=await download.path();
    const csv=fs.readFileSync(downloadPath,'utf8');assert.ok(csv.includes('区域人员超限'));assert.ok(csv.includes('参考视频演示'));
    await page.locator('[data-action="system"]').first().click();
    assert.ok((await page.locator('#modal-body').textContent()).includes('未连接'));
    await page.locator('#modal [data-action="close-modal"]').first().click();
    await page.locator('.check-chip').click();
    await page.locator('[data-action="run-checks"]').click();
    assert.equal(await page.locator('.check-state.pending').count(),3);
    await page.locator('#modal [data-action="close-modal"]').first().click();
    await page.locator('[data-action="upload"]').click();
    await page.locator('#video-upload').setInputFiles('assets/reference.mp4');
    await page.waitForFunction(()=>document.querySelector('#source-video').readyState>=2 && document.querySelector('#mode-text').textContent.includes('本地视频'));
    assert.equal(await page.locator('#metric-targets').textContent(),'—');
