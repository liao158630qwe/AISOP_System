// Runs against the settings page in the isolated keyboard UI fixture; no device I/O.
const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path');

module.exports = async ({page, context, base, output}) => {
  const field = name => page.locator(`#modbus-form [name="${name}"]`);
  const requests = [];
  const observe = request => {if (request.url().includes('/api/') && new URL(request.url()).pathname !== '/api/v1/session') requests.push(request.url());};
  page.on('request', observe);
  await page.locator('[aria-controls="modbus-section-content"]').click();
  await page.locator('#modbus-form').waitFor();
  assert.equal(await field('lampBrand').inputValue(), '正泰');
  assert.equal(await field('lampModel').inputValue(), 'ZTP-NP');
  assert.equal(await field('lampVoltage').inputValue(), '24V');
  assert.equal(await field('supplyType').inputValue(), '');
  assert.equal(await field('transport').inputValue(), '');
  assert.equal(await field('red.address').inputValue(), '', 'unknown hardware addresses stay blank');
  assert.ok(await page.locator('#modbus-tcp').isHidden());
  assert.ok(await page.locator('#modbus-rtu').isHidden());
  await field('transport').selectOption('tcp');
  await field('host').fill('192.0.2.10'); await field('port').fill('1502'); await field('unitId').fill('1');
  await field('moduleModel').fill('UI fixture I/O');
  await field('start.area').selectOption('discrete-input'); await field('start.address').fill('0');
  await field('start.active').selectOption('1');
  await field('stop.area').selectOption('discrete-input'); await field('stop.address').fill('0');
  assert.equal(await page.locator('#modbus-save-status').getAttribute('data-error'), 'true');
  assert.match(await field('stop.address').evaluate(n => n.validationMessage), /重叠/);
  await field('stop.address').fill('1');
  await field('red.area').selectOption('coil'); await field('red.address').fill('65536');
  assert.equal(await page.locator('#modbus-save-status').getAttribute('data-error'), 'true');
  await field('red.address').fill('0'); await field('red.active').selectOption('1');
  assert.equal(await page.locator('#modbus-save-status').getAttribute('data-error'), 'false');
  await field('green.area').selectOption('holding-register'); await field('green.address').fill('10'); await field('green.bit').fill('0');
  await field('yellow.area').selectOption('holding-register'); await field('yellow.address').fill('10');
  assert.equal(await page.locator('#modbus-save-status').getAttribute('data-error'), 'true', 'whole-register mapping conflicts with a bit mapping');
  await field('yellow.bit').fill('1');
  assert.equal(await page.locator('#modbus-save-status').getAttribute('data-error'), 'false', 'separate register bits can coexist');
  await field('buzzerControl').selectOption('linked'); assert.ok(await field('buzzer.address').isDisabled());
  await field('buzzerControl').selectOption('independent'); assert.ok(await field('buzzer.address').isEnabled());
  const preview = page.locator('#modbus-preview-state');
  await preview.selectOption('fail');
  assert.equal(await page.locator('[data-lamp="red"].is-on.is-flashing').count(), 1);
  assert.equal(await page.locator('#modbus-preview-buzzer').getAttribute('data-on'), 'true');
  await field('rule.fail.light').selectOption('red'); await field('rule.fail.sound').uncheck();
  assert.equal(await page.locator('[data-lamp="red"].is-flashing').count(), 0);
  assert.equal(await page.locator('#modbus-preview-buzzer').getAttribute('data-on'), 'false');
  await page.locator('[data-modbus-preview="running"]').click();
  assert.equal(await page.locator('[data-lamp="yellow"].is-on.is-flashing').count(), 1);
  await page.locator('[data-modbus-preview="idle"]').click();
  assert.equal(await page.locator('[data-lamp="yellow"].is-on:not(.is-flashing)').count(), 1);
  await preview.selectOption('pass');
  assert.equal(await page.locator('[data-lamp="green"].is-on').count(), 1);
  // Each station stores its own transport, map and rules.
  await page.locator('#modbus-station').selectOption('station-2');
  assert.equal(await field('transport').inputValue(), '');
  assert.equal(await field('red.address').inputValue(), '');
  assert.ok(await field('rule.fail.sound').isChecked());
  await field('transport').selectOption('rtu'); await field('serialPort').fill('COM3');
  await field('baudRate').selectOption('19200'); await field('parity').selectOption('E');
  assert.ok(await page.locator('#modbus-tcp').isHidden());
  await page.locator('#modbus-station').selectOption('station-1');
  assert.equal(await field('host').inputValue(), '192.0.2.10');
  assert.equal(await field('red.address').inputValue(), '0');
  assert.equal(await field('rule.fail.light').inputValue(), 'red');
  await page.reload(); await page.locator('[aria-controls="modbus-section-content"]').click(); await page.locator('#modbus-form').waitFor();
  assert.equal(await field('host').inputValue(), '192.0.2.10');
  // A second settings page edits another station without overwriting the first.
  const peer = await context.newPage(); await peer.goto(base + '/settings');
  await peer.locator('[aria-controls="modbus-section-content"]').click();
  await peer.locator('#modbus-station').selectOption('station-3');
  await peer.locator('[name="moduleModel"]').fill('Station 3 module');
  await peer.close(); await page.bringToFront();
  assert.equal(await field('host').inputValue(), '192.0.2.10');
  const downloading = page.waitForEvent('download'); await page.locator('#modbus-export').click();
  const download = await downloading, exportedPath = path.join(output, 'modbus-drafts.json');
  await download.saveAs(exportedPath);
  const exported = JSON.parse(fs.readFileSync(exportedPath, 'utf8'));
  assert.equal(exported.status, 'draft'); assert.equal(exported.hardwareVerified, false);
  assert.equal(Object.keys(exported.stations).length, 6);
  assert.equal(exported.stations['station-1'].values['red.address'], '0');
  assert.equal(exported.stations['station-2'].values.serialPort, 'COM3');
  assert.equal(exported.stations['station-3'].values.moduleModel, 'Station 3 module');
  assert.equal(exported.stations['station-6'].values.transport, '');
  await page.locator('#modbus-settings').screenshot({path: path.join(output, 'modbus-settings-desktop.png')});
  for (const width of [768, 390, 320]) {
    await page.setViewportSize({width, height: 900});
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Modbus settings fit at ' + width);
  }
  await page.locator('#modbus-settings').screenshot({path: path.join(output, 'modbus-settings-mobile.png')});
  await page.setViewportSize({width: 1440, height: 1050});
  assert.deepEqual(requests, [], 'saving and previewing device drafts never sends device or detection API requests');
  page.off('request', observe);
  await page.locator('[aria-controls="trigger-section-content"]').click();
};
