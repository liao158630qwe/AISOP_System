"""Independent assisted workflows for six stations, without model inference."""
import base64
import binascii
import copy
import hashlib
import io
import json
import os
import uuid
from typing import Annotated, Literal

from fastapi import APIRouter, HTTPException, Query, Request
from fastapi.responses import FileResponse
from PIL import Image, UnidentifiedImageError
from pydantic import BaseModel, ConfigDict, Field, StringConstraints
from sqlalchemy import select, update, func, or_
from sqlalchemy.exc import IntegrityError, SQLAlchemyError

from .db import now, pilot_cycles as cycles, pilot_events as events
from .pilot_config import STATIONS, stages, final_stages

CONFIG = STATIONS['station-1']
StationID = Literal['station-1', 'station-2', 'station-3', 'station-4', 'station-5', 'station-6']


class Strict(BaseModel):
    model_config = ConfigDict(extra='forbid', str_strip_whitespace=True, allow_inf_nan=False)


class Start(Strict):
    request_id: uuid.UUID
    station: StationID = 'station-1'
    part_number: str = Field(default='', max_length=100)
    product: str = Field(min_length=1, max_length=100)
    source: Literal['camera', 'image', 'replay']
    parent_id: uuid.UUID | None = None


class Manual(Strict):
    request_id: uuid.UUID
    revision: int = Field(ge=1)
    review_password: Annotated[str, StringConstraints(strip_whitespace=False, min_length=1, max_length=200)]
    reason: str = Field(min_length=2, max_length=1000)


class Stage(Manual):
    stage: str = Field(min_length=1, max_length=24, pattern=r'^[A-Z_]+$')
    checked: list[str] = Field(min_length=1, max_length=100)
    image: str = Field(min_length=10, max_length=2800000)
    media_time: float | None = Field(default=None, ge=0, le=86400)
    captured_at: float | None = Field(default=None, ge=0)


class Close(Manual):
    outcome: Literal['NG', 'REVIEW', 'INTERRUPTED']
    image: str | None = Field(default=None, max_length=2800000)


class Review(Manual):
    disposition: Literal['note', 'confirmed_ng', 'needs_rework']


def public(row):
    result = {k: row[k] for k in ('id', 'station', 'part_number', 'product', 'source', 'parent_id',
        'stage', 'result', 'review_status', 'revision', 'config', 'checks', 'reason', 'started_at', 'updated_at', 'finished_at')}
    result['operator'] = row['owner']
    result['algorithm_result'] = 'NOT_EVALUATED'
    result['record_kind'] = '现场人工试跑' if row['source'] == 'camera' else '回放图片联调'
    result['config'] = dict(row['config'], stages=stages(row['config']))
    return result


def decode_evidence(encoded):
    try:
        data = base64.b64decode(encoded, validate=True)
        if len(data) > 2 * 1024 * 1024:
            raise ValueError()
        with Image.open(io.BytesIO(data)) as picture:
            if picture.format not in ('JPEG', 'PNG') or not (32 <= picture.width <= 2560 and 32 <= picture.height <= 2560):
                raise ValueError()
            picture.load()
            output = io.BytesIO()
            picture.convert('RGB').save(output, 'JPEG', quality=90)
        return output.getvalue()
    except (ValueError, binascii.Error, OSError, UnidentifiedImageError, Image.DecompressionBombError) as exc:
        raise HTTPException(422, '证据须为2MB以内、32至2560像素的有效JPEG或PNG图像') from exc


class Pilot:
    def __init__(self, engine, settings):
        self.engine = engine
        self.root = settings.data_dir / 'pilot-evidence'
        self.registration_enabled = settings.pilot_registration_enabled

    def config(self, station):
        return dict(STATIONS[station], registration_enabled=self.registration_enabled)

    def _get(self, c, owner, identity):
        row = c.execute(select(cycles).where(cycles.c.id == identity, cycles.c.owner == owner)).mappings().first()
        if not row:
            raise HTTPException(404, '工位记录不存在')
        return dict(row)

    def _replay(self, c, owner, key, signature):
        event = c.execute(select(events).where(events.c.owner == owner, events.c.request_key == key)).mappings().first()
        if event:
            if event['request_hash'] != signature:
                raise HTTPException(409, '该请求编号已用于其他操作，请刷新后重试')
            return event['response']

    def _file(self, identity, evidence):
        # IDs and filenames are generated by the server, never taken from a path parameter.
        return self.root / identity / evidence['name']

    def _write(self, identity, data, written):
        folder = self.root / identity
        folder.mkdir(parents=True, exist_ok=True)
        path = folder / (str(uuid.uuid4()) + '.jpg')
        temp = path.with_suffix('.part')
        written.extend([temp, path])
        with temp.open('xb') as handle:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        temp.replace(path)
        return {'name': path.name, 'sha256': hashlib.sha256(data).hexdigest(),
                'url': f'/api/v1/pilot/cycles/{identity}/evidence/{path.name}'}

    def _verify_proofs(self, row):
        for stage in stages(row['config']):
            check = row['checks'].get(stage['id'])
            if not check or check['items'] != [item['id'] for item in stage['items']]:
                raise HTTPException(409, '本工位检查项目尚未全部确认')
            path = self._file(row['id'], check['evidence'])
            if not path.is_file() or hashlib.sha256(path.read_bytes()).hexdigest() != check['evidence']['sha256']:
                raise HTTPException(409, '阶段证据缺失或损坏，不能通过；请中断后重新检查')

    def command(self, owner, body, kind, identity=None):
        key = str(body.request_id)
        clean = body.model_dump(mode='json', exclude={'review_password'})
        if kind == 'START' and body.station == 'station-1':
            clean.pop('station', None)  # Preserve original station-1 retry signatures.
        # Preserve request signatures for clients predating capture timestamps.
        if kind == 'STAGE' and body.captured_at is None:
            clean.pop('captured_at', None)
        signature = hashlib.sha256(json.dumps([kind, identity, clean], sort_keys=True).encode()).hexdigest()
        written = []
        try:
            with self.engine.begin() as c:
                replay = self._replay(c, owner, key, signature)
                if replay:
                    return replay
                t = now(c)
                if kind == 'START':
                    if not self.registration_enabled:
                        raise HTTPException(409, '工位1–6工件登记暂已停用，可在检测首页按F8开始工位检测')
                    config = STATIONS[body.station]
                    if c.execute(select(cycles.c.id).where(cycles.c.active_station == body.station)).first():
                        raise HTTPException(409, config['name'] + '已有未结束周期，请恢复当前工件或先结束为中断')
                    parent = self._get(c, owner, str(body.parent_id)) if body.parent_id else None
                    if parent and parent['station'] != body.station:
                        raise HTTPException(409, '返工须在原工位进行')
                    if parent and parent['stage'] != 'CLOSED':
                        raise HTTPException(409, '请先结束原周期再返工')
                    if parent and (body.product != parent['product'] or body.part_number != parent['part_number']):
                        raise HTTPException(409, '返工须沿用原产品和工件编号')
                    identity = str(uuid.uuid4())
                    row = dict(id=identity, owner=owner, station=body.station, active_station=body.station,
                        part_number=body.part_number or 'TMP-' + identity[:12].upper(), product=body.product,
                        source=body.source, parent_id=str(body.parent_id) if body.parent_id else None,
                        stage=stages(config)[0]['id'], result=None, review_status=None, revision=1, config=copy.deepcopy(config), checks={}, reason='',
                        started_at=t, updated_at=t, finished_at=None)
                    c.execute(cycles.insert().values(**row))
                    payload = {'source': row['source'], 'parent_id': row['parent_id']}
                else:
                    row = self._get(c, owner, identity)
                    if row['revision'] != body.revision:
                        raise HTTPException(409, '记录已更新，请刷新后核对当前阶段再操作')
                    if kind != 'REVIEW' and row['stage'] == 'CLOSED':
                        raise HTTPException(409, '该周期已结束；复核追加记录，返工建立新周期')
                    payload = {'reason': body.reason, 'actor': owner, 'source': 'manual', 'reauthenticated': True}
                    row['checks'] = copy.deepcopy(row['checks'])
                    if kind == 'STAGE':
                        # Check only after idempotent replay: an acknowledged commit stays
                        # retrievable, but retrying an uncommitted old image cannot renew it.
                        if body.captured_at is not None and not -30 <= t - body.captured_at <= 120:
                            raise HTTPException(409, '取证已过期或终端时钟异常，请核对时钟并重新取证')
                        definition = next((item for item in stages(row['config']) if item['id'] == body.stage), None)
                        if not definition:
                            raise HTTPException(422, '该检查项目不属于当前工位')
                        expected = [item['id'] for item in definition['items']]
                        if sorted(body.checked) != sorted(expected):
                            raise HTTPException(422, f'请逐项确认本阶段{len(expected)}个指定项目，不得重复或替代')
                        if any(required not in row['checks'] for required in definition['requires']):
                            raise HTTPException(409, '须先完成并保存前置阶段证据，再检查本项目')
                        if body.stage in row['checks'] and not (row['stage'] == 'READY' and definition in final_stages(row['config'])):
                            raise HTTPException(409, '该阶段已经确认；仅全部完成后可重新核对末端项目')
                        if row['source'] == 'replay' and body.media_time is None:
                            raise HTTPException(422, '回放证据须包含视频时间')
                        if row['source'] == 'replay' and any(body.media_time <= row['checks'][required]['media_time'] for required in definition['requires']):
                            raise HTTPException(409, '本阶段证据必须来自前置阶段确认之后的视频时点')
                        evidence = self._write(identity, decode_evidence(body.image), written)
                        proof = dict(payload, items=expected, evidence=evidence, at=t,
                                     media_time=body.media_time, algorithm_result='NOT_EVALUATED')
                        if body.captured_at is not None:
                            proof['captured_at'] = min(t, body.captured_at)
                        row['checks'][body.stage] = proof
                        row['stage'] = next((item['id'] for item in stages(row['config']) if item['id'] not in row['checks']
                                             and all(required in row['checks'] for required in item['requires'])), 'READY')
                        payload = dict(proof, stage=body.stage)
                    elif kind == 'FINISH':
                        if row['stage'] != 'READY':
                            raise HTTPException(409, '请先保存本工位全部检查项目的确认与证据')
                        self._verify_proofs(row)
                        for item in final_stages(row['config']):
                            proof = row['checks'][item['id']]
                            if t - min(proof['at'], proof.get('captured_at', proof['at'])) > row['config']['final_evidence_max_age_seconds']:
                                raise HTTPException(409, item['name'] + '证据已超过3分钟，请重新核对该项目并取证')
                        pending = row['config'].get('pending_specs', [])
                        # The full operator reason remains in the event payload.
                        reason = (('工艺要求待确认：' + '、'.join(pending) + '；' if pending else '') + body.reason)[:1000]
                        row.update(stage='CLOSED', result='REVIEW' if pending else 'MANUAL_OK', active_station=None, finished_at=t, reason=reason)
                        payload['pending_specs'] = pending
                    elif kind == 'CLOSE':
                        if body.image:
                            payload['evidence'] = self._write(identity, decode_evidence(body.image), written)
                        payload['evidence_missing'] = not bool(body.image)
                        payload['outcome'] = body.outcome
                        row.update(stage='CLOSED', result=body.outcome, active_station=None, finished_at=t, reason=body.reason)
                    elif kind == 'REVIEW':
                        if row['stage'] != 'CLOSED':
                            raise HTTPException(409, '请先结束本轮，再追加复核记录')
                        payload['disposition'] = body.disposition
                        if body.disposition != 'note':
                            row['review_status'] = body.disposition
                    row.update(revision=row['revision'] + 1, updated_at=t)
                    changed = c.execute(update(cycles).where(cycles.c.id == identity, cycles.c.revision == body.revision).values(
                        **{k: row[k] for k in ('checks', 'stage', 'result', 'review_status', 'revision', 'reason', 'updated_at', 'active_station', 'finished_at')}))
                    if changed.rowcount != 1:
                        raise HTTPException(409, '其他页面已更新该周期，请刷新后核对')
                response = {'cycle': public(row)}
                c.execute(events.insert().values(id=str(uuid.uuid4()), cycle_id=identity, owner=owner,
                    request_key=key, request_hash=signature, kind=kind, revision=row['revision'], at=t,
                    payload=payload, response=response))
            return response
        except BaseException as exc:
            # A lost database connection during COMMIT has an unknown outcome.
            # Never remove evidence if the commit succeeded or cannot be checked.
            if isinstance(exc, SQLAlchemyError) and not isinstance(exc, IntegrityError):
                try:
                    with self.engine.connect() as c:
                        replay = self._replay(c, owner, key, signature)
                    if replay:
                        return replay
                except SQLAlchemyError:
                    raise HTTPException(503, '保存状态暂无法确认，请恢复数据库连接后使用同一请求重试') from exc
            for path in written:
                try:
                    path.unlink(missing_ok=True)
                except OSError:
                    pass
            if isinstance(exc, IntegrityError):
                with self.engine.connect() as c:
                    replay = self._replay(c, owner, key, signature)
                if replay:
                    return replay
                raise HTTPException(409, '工位或记录已被其他操作更新，请刷新后重试') from exc
            if isinstance(exc, (OSError, SQLAlchemyError)):
                raise HTTPException(503, '保存失败，尚未确认完成。请检查存储后使用同一请求重试') from exc
            raise

    def detail(self, owner, identity):
        with self.engine.connect() as c:
            row = self._get(c, owner, identity)
            history = c.execute(select(events).where(events.c.cycle_id == identity).order_by(events.c.revision)).mappings().all()
            children = c.execute(select(cycles.c.id).where(cycles.c.parent_id == identity, cycles.c.owner == owner)).scalars().all()
        return {'cycle': public(row), 'events': [{k: e[k] for k in ('id', 'kind', 'revision', 'at', 'payload')} for e in history],
                'rework_ids': children}


def register(app, auth, verify_manual):
    pilot = Pilot(app.state.engine, app.state.settings)
    app.state.pilot = pilot
    router = APIRouter(prefix='/api/v1/pilot')

    @router.get('/stations')
    def catalog():
        return {'items': [pilot.config(station) for station in STATIONS]}

    @router.get('/status')
    def status(request: Request, station: StationID = 'station-1'):
        user = auth(request)
        app.state.terminals.require_station(user, station)
        owner = user['owner']
        with pilot.engine.connect() as c:
            row = c.execute(select(cycles).where(cycles.c.active_station == station)).mappings().first()
        writable = True
        probe = pilot.root / ('.probe-' + str(uuid.uuid4()))
        try:
            pilot.root.mkdir(parents=True, exist_ok=True)
            with probe.open('xb') as handle:
                handle.write(b'pilot-storage-check')
                handle.flush()
                os.fsync(handle.fileno())
        except OSError:
            writable = False
        finally:
            try:
                probe.unlink(missing_ok=True)
            except OSError:
                writable = False
        return {'config': pilot.config(station), 'storage_ready': writable, 'occupied': bool(row),
                'active': public(row) if row and row['owner'] == owner else None}

    @router.get('/cycles')
    def history(request: Request, station: StationID = 'station-1', q: str = Query(default='', max_length=100),
                offset: int = Query(default=0, ge=0, le=1000000), limit: int = Query(default=20, ge=1, le=100)):
        user = auth(request)
        app.state.terminals.require_station(user, station)
        owner = user['owner']
        condition = [cycles.c.owner == owner, cycles.c.station == station]
        if q.strip():
            condition.append(or_(cycles.c.part_number.contains(q.strip(), autoescape=True),
                                 cycles.c.product.contains(q.strip(), autoescape=True)))
        with pilot.engine.connect() as c:
            total = c.execute(select(func.count()).select_from(cycles).where(*condition)).scalar_one()
            rows = c.execute(select(cycles).where(*condition).order_by(cycles.c.started_at.desc(), cycles.c.id.desc())
                             .offset(offset).limit(limit)).mappings().all()
        return {'items': [public(row) for row in rows], 'total': total, 'offset': offset}

    @router.post('/cycles', status_code=201)
    def start(body: Start, request: Request):
        user = auth(request)
        app.state.terminals.require_station(user, body.station)
        return pilot.command(user['owner'], body, 'START')

    @router.get('/cycles/{identity}')
    def detail(identity: uuid.UUID, request: Request):
        user = auth(request)
        result = pilot.detail(user['owner'], str(identity))
        app.state.terminals.require_station(user, result['cycle']['station'])
        return result

    def execute(identity, body, request, kind):
        user = auth(request)
        row = pilot.detail(user['owner'], str(identity))
        app.state.terminals.require_station(user, row['cycle']['station'])
        verify_manual(request, body.review_password)
        return pilot.command(user['owner'], body, kind, str(identity))

    @router.post('/cycles/{identity}/stage')
    def stage(identity: uuid.UUID, body: Stage, request: Request):
        return execute(identity, body, request, 'STAGE')

    @router.post('/cycles/{identity}/finish')
    def finish(identity: uuid.UUID, body: Manual, request: Request):
        return execute(identity, body, request, 'FINISH')

    @router.post('/cycles/{identity}/close')
    def close(identity: uuid.UUID, body: Close, request: Request):
        return execute(identity, body, request, 'CLOSE')

    @router.post('/cycles/{identity}/review')
    def review(identity: uuid.UUID, body: Review, request: Request):
        return execute(identity, body, request, 'REVIEW')

    @router.post('/cycles/{identity}/resume')
    def resume(identity: uuid.UUID, body: Manual, request: Request):
        return execute(identity, body, request, 'RESUME')

    @router.get('/cycles/{identity}/evidence/{name}')
    def evidence(identity: uuid.UUID, name: str, request: Request):
        user = auth(request)
        history = pilot.detail(user['owner'], str(identity))
        app.state.terminals.require_station(user, history['cycle']['station'])
        proofs = [e['payload'].get('evidence') for e in history['events']]
        proof = next((p for p in proofs if p and p['name'] == name), None)
        if not proof:
            raise HTTPException(404, '证据不存在')
        path = pilot._file(str(identity), proof)
        if not path.is_file():
            raise HTTPException(404, '证据文件缺失')
        return FileResponse(path, media_type='image/jpeg')

    app.include_router(router)
